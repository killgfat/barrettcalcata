def _to_float(text):
    """空字段返回 None，否则转 float。"""
    return float(text) if text else None


def _to_int(text):
    """空字段返回 None，否则转 int。"""
    return int(text) if text else None


def _to_haigis(text):
    """解析 a0,a1,a2；缺任一值返回 None。"""
    if not text:
        return None
    parts = text.split(",")
    if len(parts) != 3 or not all(parts):
        return None
    return tuple(float(item) for item in parts)


def iter_rows():
    """逐行解析快照，返回 (name, nominal, haigis, pacd, sf, srkt, srk2, n)。"""
    for line in ULIB_RAW.strip().splitlines():
        if not line or line.startswith("#"):
            continue
        fields = line.split("|")
        if len(fields) != 8:
            raise ValueError(f"ULIB 快照行格式错误：{line!r}")
        name, nominal, haigis, pacd, sf, srkt, srk2, samples = fields
        yield (
            name,
            _to_float(nominal),
            _to_haigis(haigis),
            _to_float(pacd),
            _to_float(sf),
            _to_float(srkt),
            _to_float(srk2),
            _to_int(samples),
        )


